import { pool } from '../config/db.js';
import { distanceKm, sortByDistance } from '../utils/geo.js';

/** Shortest distance from point P to segment AB, in km (approx, planar). */
function pointToSegmentDistanceKm(p, a, b) {
  const toXY = (pt) => ({ x: pt.lng, y: pt.lat });
  const P = toXY(p), A = toXY(a), B = toXY(b);
  const dx = B.x - A.x, dy = B.y - A.y;
  const lengthSq = dx * dx + dy * dy;
  let t = lengthSq === 0 ? 0 : ((P.x - A.x) * dx + (P.y - A.y) * dy) / lengthSq;
  t = Math.max(0, Math.min(1, t));
  const closest = { lat: A.y + t * dy, lng: A.x + t * dx };
  return distanceKm(p.lat, p.lng, closest.lat, closest.lng);
}

const DETOUR_TRIGGER_KM = 1.0;

/**
 * Simulated "safe route" engine. Sahayta does not have a live routing/traffic
 * provider connected, so this builds a realistic waypoint path between two
 * points and flags/avoids known blocked roads and active high-severity
 * incidents near the straight-line path. Swap this for a real routing API
 * (e.g. OSRM/Mapbox) by keeping the same input/output contract.
 */
export async function computeSafeRoute({ start_lat, start_lng, end_lat, end_lng }) {
  const start = { lat: start_lat, lng: start_lng };
  const end = { lat: end_lat, lng: end_lng };

  const [{ rows: blockedRoads }, { rows: incidents }, { rows: hospitals }, { rows: shelters }] = await Promise.all([
    pool.query(`select * from blocked_roads where expires_at is null or expires_at > now()`),
    pool.query(`select * from incident_reports where status = 'verified' and severity in ('high','critical')`),
    pool.query(`select * from hospitals where available_beds > 0`),
    pool.query(`select * from shelters where status = 'open' and occupied < capacity`),
  ]);

  const warnings = [];
  const avoided = [];
  let waypoints = [start, end];

  for (const road of blockedRoads) {
    const dist = pointToSegmentDistanceKm(
      { lat: (start.lat + end.lat) / 2, lng: (start.lng + end.lng) / 2 },
      { lat: road.lat_start, lng: road.lng_start },
      { lat: road.lat_end, lng: road.lng_end }
    );
    if (dist < DETOUR_TRIGGER_KM) {
      avoided.push({ label: road.label, reason: road.reason, severity: road.severity });
      // Insert a detour waypoint perpendicular-ish to the midpoint, offset away from the blockage.
      const mid = { lat: (start.lat + end.lat) / 2, lng: (start.lng + end.lng) / 2 };
      const offsetLat = mid.lat + (mid.lat >= road.lat_start ? 0.01 : -0.01);
      const offsetLng = mid.lng + (mid.lng >= road.lng_start ? 0.01 : -0.01);
      waypoints = [start, { lat: offsetLat, lng: offsetLng, detour_for: road.label }, end];
    }
  }

  const nearbyIncidents = incidents.filter((inc) => {
    const dist = pointToSegmentDistanceKm({ lat: inc.latitude, lng: inc.longitude }, start, end);
    return dist < DETOUR_TRIGGER_KM;
  });
  nearbyIncidents.forEach((inc) => warnings.push(`Active ${inc.severity} ${inc.emergency_type} incident near route: ${inc.title}`));

  let riskLevel = 'LOW';
  if (nearbyIncidents.some((i) => i.severity === 'critical') || avoided.length > 1) riskLevel = 'HIGH';
  else if (nearbyIncidents.length || avoided.length) riskLevel = 'MEDIUM';

  const totalDistanceKm = waypoints.reduce((sum, wp, i) => {
    if (i === 0) return 0;
    return sum + distanceKm(waypoints[i - 1].lat, waypoints[i - 1].lng, wp.lat, wp.lng);
  }, 0);

  const nearestHospital = hospitals.length ? sortByDistance(hospitals, end.lat, end.lng)[0] : null;
  const nearestShelter = shelters.length ? sortByDistance(shelters, end.lat, end.lng)[0] : null;

  return {
    waypoints,
    distance_km: Number(totalDistanceKm.toFixed(2)),
    estimated_minutes: Math.max(3, Math.round((totalDistanceKm / 30) * 60)), // assume ~30km/h average urban crisis-driving speed
    risk_level: riskLevel,
    avoided_roads: avoided,
    warnings,
    nearest_hospital: nearestHospital,
    nearest_shelter: nearestShelter,
    is_simulated: true,
    note: 'Route generated by Sahayta\'s simulation layer (no live traffic/routing provider connected). Structure is compatible with a real routing API.',
  };
}

export async function listBlockedRoads() {
  const { rows } = await pool.query(
    `select br.*, u.name as reported_by_name from blocked_roads br left join users u on u.id = br.reported_by
     where br.expires_at is null or br.expires_at > now() order by br.created_at desc`
  );
  return rows;
}

export async function reportBlockedRoad(payload, reportedBy) {
  const { rows } = await pool.query(
    `insert into blocked_roads (label, reason, severity, lat_start, lng_start, lat_end, lng_end, reported_by)
     values ($1,$2,$3,$4,$5,$6,$7,$8) returning *`,
    [payload.label, payload.reason || null, payload.severity || 'medium', payload.lat_start, payload.lng_start, payload.lat_end, payload.lng_end, reportedBy]
  );
  return rows[0];
}
